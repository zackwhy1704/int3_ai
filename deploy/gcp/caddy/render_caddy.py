#!/usr/bin/env python3
"""Generate the Caddyfile from the routes table. Stdlib only; runs on the VM.

One site per host, each with its own certificate. https only:
  * TLS-ALPN-01 only, so port 80 stays closed and no plain-http listener or redirect exists
    (.app is HSTS preloaded; nothing should ever be reachable over http);
  * Host is rewritten to the loopback form: stock Hermes binds 127.0.0.1 and refuses any other Host
    on /api/ws (hermes_cli/web_server_boundary.py:84-108, 197-222 @v0.22.6), so the backend sees
    exactly what it sees on a local stack;
  * X-Forwarded-* is removed: Hermes always trusts loopback peers to supply those
    (config_defaults.py:1000), and our proxies reach it from loopback;
  * no `log` directive: no access log, so a ?token= on a websocket URL is never written down.
"""
import argparse
import re
import sys
from pathlib import Path

STAGING = "https://acme-staging-v02.api.letsencrypt.org/directory"
ID_RE = re.compile(r"^[a-f0-9]{16}$")
BASE_RE = re.compile(r"^[a-z0-9-]+(\.[a-z0-9-]+)+$")


def read_routes(text: str) -> list[tuple[str, int]]:
    routes, seen = [], set()
    for n, line in enumerate(text.splitlines(), 1):
        if not line.strip():
            continue
        fields = line.split("\t")
        if len(fields) != 4 or not ID_RE.match(fields[0]) or not fields[1].isdigit():
            raise ValueError(f"routes line {n} is malformed")
        if fields[0] in seen or fields[1] in {str(p) for _, p in routes}:
            raise ValueError(f"routes line {n} repeats a host or a port")
        seen.add(fields[0])
        routes.append((fields[0], int(fields[1])))
    return routes


def render(routes: list[tuple[str, int]], base: str, issuer: str) -> str:
    if not BASE_RE.match(base):
        raise ValueError(f"bad base domain: {base}")
    if issuer == "production":
        acme = "\t\tissuer acme {\n\t\t\tdisable_http_challenge\n\t\t}\n"
    elif issuer == "staging":
        acme = f"\t\tissuer acme {{\n\t\t\tdir {STAGING}\n\t\t\tdisable_http_challenge\n\t\t}}\n"
    elif issuer == "internal":  # tests only: no ACME request at all
        acme = "\t\tissuer internal\n"
    else:
        raise ValueError(f"bad issuer: {issuer}")
    out = [
        "# Generated by deploy/gcp/caddy/render_caddy.py. Do not edit.\n"
        "{\n\tauto_https disable_redirects\n\tservers {\n\t\tprotocols h1 h2\n\t}\n}\n"
    ]
    for rid, port in routes:
        out.append(
            f"https://{rid}.{base} {{\n"
            f"\ttls {{\n{acme}\t}}\n"
            '\theader Strict-Transport-Security "max-age=31536000"\n'
            f"\treverse_proxy 127.0.0.1:{port} {{\n"
            f"\t\theader_up Host 127.0.0.1:{port}\n"
            "\t\theader_up -X-Forwarded-For\n"
            "\t\theader_up -X-Forwarded-Proto\n"
            "\t\theader_up -X-Forwarded-Host\n"
            "\t}\n}\n"
        )
    return "\n".join(out)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--routes", required=True)
    ap.add_argument("--base", required=True)
    ap.add_argument("--issuer", default="production")
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    try:
        text = render(read_routes(Path(a.routes).read_text(encoding="utf-8")), a.base, a.issuer)
    except ValueError as e:
        sys.exit(f"render_caddy: {e}")
    Path(a.out).write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
